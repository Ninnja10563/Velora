import { expect, test } from "@playwright/test";
import { mkdir } from "node:fs/promises";

const fixture = "http://127.0.0.1:54321";
const name = "Fixture wireless headphones A";
test("fixture catalog, signup confirmation, cloud sync, and monitored-alert controls work in the browser", async ({ page }) => {
  test.setTimeout(240_000);
  await page.request.post(`${fixture}/__fixture/reset`);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.locator("html")).toHaveAttribute("data-theme", /light|dark/, { timeout: 60_000 });
  await page.getByRole("textbox", { name: "What are you looking for?" }).fill("Wireless headphones under $100");
  await page.getByRole("spinbutton", { name: "Maximum budget" }).fill("100");
  await page.getByRole("button", { name: "Find my match", exact: true }).click();
  const resultCard = page.getByRole("article").filter({ has: page.getByRole("button", { name, exact: true }) });
  await expect(resultCard).toBeVisible();
  await resultCard.getByRole("button", { name: `Save ${name}`, exact: true }).click();
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: /Saved products/ }).click();
  await page.reload();
  await expect(resultCard).toBeVisible();
  await resultCard.getByRole("button", { name: `Details for ${name}`, exact: true }).click();
  await expect(page.getByRole("heading", { level: 1, name, exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Local protocol fixture — synthetic, not a live retailer", exact: true })).toHaveAttribute("href", "https://retailer.example/products/fixture-headphones-a");

  await page.getByRole("link", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await page.getByLabel("Your name", { exact: true }).fill("Fixture Shopper");
  await page.getByLabel("Email", { exact: true }).fill("browser@fixture.example");
  await page.getByLabel(/^Password/).fill("Fixture-password-123!");
  await page.locator("form").getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByText("Check your email to confirm your account, then sign in.", { exact: true })).toBeVisible();
  const users = await (await page.request.get(`${fixture}/__fixture/users`)).json();
  const user = users.users.find((entry: { email: string }) => entry.email === "browser@fixture.example");
  await page.goto(`/auth/confirm?token_hash=${encodeURIComponent(user.tokenHash)}&type=signup`);
  await page.getByRole("button", { name: "Confirm email link", exact: true }).click();
  await expect(page.getByText("Your email is confirmed. You’re signed in.", { exact: true })).toBeVisible();
  expect(new URL(page.url()).search).toBe("");
  await page.getByRole("link", { name: "Return to Velora", exact: true }).click();
  const synced = page.waitForResponse(response => response.url().endsWith("/api/account") && response.request().method() === "PUT");
  await page.getByRole("button", { name: "Sync this workspace", exact: true }).click();
  expect((await synced).status()).toBe(200);
  await expect(page.getByRole("button", { name: "Sync this workspace", exact: true })).toBeEnabled();
  const account = await (await page.request.get("/api/account")).json();
  expect(account.state.savedProductIds).toContain("fixture-headphones-a");
  await mkdir("outputs", { recursive: true });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "outputs/velora-fixture-account.png", fullPage: true, style: "nextjs-portal{display:none!important}" });

  await page.goto("/product/fixture-headphones-a");
  await page.getByRole("button", { name: "Set a price target", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "A price that works for you." });
  await dialog.getByRole("spinbutton", { name: "Target price (USD)" }).fill("95.50");
  await dialog.getByRole("button", { name: "Create price alert", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: /Price watchlist/ }).click();
  await expect(page.getByText("Monitoring enabled", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await expect(page.getByText("Paused", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.getByText("Monitoring enabled", { exact: true })).toBeVisible();
  expect((await page.request.post("/api/cron/price-alerts")).status()).toBe(403);
  const run = await page.request.post("/api/cron/price-alerts", { headers: { Authorization: "Bearer fixture-cron-secret-do-not-use-in-production" } });
  expect(run.status(), await run.text()).toBe(200);
  expect(await run.json()).toMatchObject({ checked: 1, notified: 1, failed: 0 });
  await page.getByRole("button", { name: "Refresh alerts", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Recent notifications", exact: true })).toBeVisible();
  await expect(page.getByText(/Delivery is in-app only; no notification emails are sent/)).toBeVisible();
  await page.getByRole("button", { name: "Price history", exact: true }).click();
  await expect(page.getByRole("table", { name: "Recorded retailer prices" })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "outputs/velora-fixture-monitoring.png", fullPage: true, style: "nextjs-portal{display:none!important}" });
  await page.getByRole("button", { name: "Mark read", exact: true }).click();
  await expect(page.getByRole("button", { name: "Mark read", exact: true })).not.toBeVisible();
  expect(errors).toEqual([]);
});
